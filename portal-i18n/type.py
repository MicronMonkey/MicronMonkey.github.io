"""Writes portal-type.css: one font size per text category (A–H).

Phone sizes are the ones asked for (pt at a 390px-wide phone); desktop sizes
keep each category's original desktop/phone ratio. Between 390px and 1024px
the size grows smoothly. Run: python3 portal-i18n/type.py
"""
