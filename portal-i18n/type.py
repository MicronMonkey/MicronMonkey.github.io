def px(v):
    return f'{v * PT:.2f}'.rstrip('0').rstrip('.') + 'px'


out = ['/* Generated by type.py: font size per text category (phone = 390px, desktop = 1024px and up) */', ':root {']
for k, (m, d) in SIZES.items():
    if m == d:
        out.append(f'  --t-{k}: {px(m)};')
    else:
        slope = (d - m) * PT / 634
        out.append(f'  --t-{k}: clamp({px(m)}, calc({px(m)} + (100vw - 390px) * {slope:.5f}), {px(d)});')
out.append('}')
for k, sels in RULES.items():
    full = []
    for s in sels:
        base = 'html[data-portal-lang] ' + s
        full += [base, base + ' .u-bilingual', base + ' .u-zh', base + ' .u-en']
    out.append(',\n'.join(full) + f' {{ font-size: var(--t-{k}) !important; }}')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'portal-type.css'), 'w', encoding='utf8').write('\n'.join(out) + '\n')
print('ok')
