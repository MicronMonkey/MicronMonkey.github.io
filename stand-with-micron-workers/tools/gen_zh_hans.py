"""Convert the zh-Hant dump to Simplified Chinese with OpenCC (pip install opencc).
usage: python3 tools/gen_zh_hans.py zh.json > i18n-zh-hans.js"""
import json, sys, opencc
cc = opencc.OpenCC('tw2sp')
src = json.load(open(sys.argv[1], encoding='utf8'))
out = {k: cc.convert(v) for k, v in src.items() if isinstance(v, str)}
out['union.full'] = '阅读公开信全文（繁体中文原文）'
print('/* Generated by tools/gen_zh_hans.py from the zh-Hant text. Do not edit by hand. */')
print('window.SWMW_I18N = window.SWMW_I18N || {};')
print("window.SWMW_I18N['zh-Hans'] = " + json.dumps(out, ensure_ascii=False, indent=0) + ';')
